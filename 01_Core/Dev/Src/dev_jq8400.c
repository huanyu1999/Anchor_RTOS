/**  
  * @brief  
  * @param  None
  * @retval None
  */
void dev_jq8400CommandData(UartCommandData Command, uint8_t DATA) {
    uint8_t Buffer[6] ={0xaa};
    uint8_t DataLen = 0;
    Buffer[1] = Command;            // 指令类型
    if((Command != AppointTrack) && (Command != SetCycleCount) && (Command != SelectTrackNoPlay) && (Command != AppointTimeBack) && (Command != AppointTimeFast)) {
        Buffer[2] = 1;              // 数据长度
        Buffer[3] = DATA;           // 数据
        Buffer[4] = Buffer[0] +  Buffer[1] +  Buffer[2] + Buffer[3];            // 校验和
        DataLen = 5;
    } else {                        // 含两个数据指令
        Buffer[2] = 2;              // 数据长度
        Buffer[3] = DATA/256;       // 数据
        Buffer[4] = DATA%256;       // 数据
        Buffer[5] = Buffer[0] +  Buffer[1] +  Buffer[2] + Buffer[3] + Buffer[4];  
        DataLen = 6;
    }
    
#if JQ8x00_BusyCheck
    while(JQ8x00_BUSY_Read);        // JQ8400 忙检测
#endif
    dev_jq8400VoiceOut(Buffer, DataLen);
}

